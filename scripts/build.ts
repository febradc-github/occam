// Bundles the in-process entry points into the committed plugin files.
// Git-based marketplaces install the repository as-is, so build outputs are committed.
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build, type BuildOptions } from "esbuild";

const repo = fileURLToPath(new URL("..", import.meta.url));
const manifest = JSON.parse(await readFile(`${repo}/plugins/occam/.claude-plugin/plugin.json`, "utf8"));
const ompPackage = JSON.parse(await readFile(`${repo}/plugins/occam/package.json`, "utf8"));
if (manifest.version !== ompPackage.version) {
  throw new Error(
    `Version mismatch: plugin.json has ${manifest.version}, package.json has ${ompPackage.version}. Claude Code reads the first, omp the second.`,
  );
}

const common: BuildOptions = {
  absWorkingDir: repo,
  bundle: true,
  format: "esm",
  target: "es2022",
  // Never minify: Claude Code's mod checker requires `$` to stay spelled as `$`.
  minify: false,
  legalComments: "none",
  banner: { js: "// Generated by scripts/build.ts. Do not edit; change src/ and rebuild." },
  define: { OCCAM_VERSION: JSON.stringify(manifest.version) },
  logLevel: "info",
};

await build({
  ...common,
  entryPoints: ["src/adapters/claude-code/mod.ts"],
  outfile: "plugins/occam/hooks/register.js",
  platform: "neutral",
});

await build({
  ...common,
  entryPoints: ["src/adapters/omp/extension.ts"],
  outfile: "plugins/occam/dist/omp-extension.js",
  platform: "node",
});
